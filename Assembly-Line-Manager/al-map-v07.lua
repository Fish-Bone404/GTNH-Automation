-- Assembly Line Manager Transposer Mapper v0.7 | GTNH 2.9
-- READ ONLY for all in-world blocks. Never moves items or fluids.
-- Saves only a local configuration file: /home/al-map-data.lua
local component=require("component")
local args={...}
local command=args[1] or "help"
local path="/home/al-map-data.lua"

local function available()
  local t={}
  for addr in component.list("transposer") do t[#t+1]=addr end
  table.sort(t)
  return t
end
local function invoke(addr,method,...)
  local ok,result=pcall(component.invoke,addr,method,...)
  if ok then return result end
  return nil
end
local function short(addr)
  return tostring(addr):sub(1,8)
end
local function load()
  local ok,c=pcall(dofile,path)
  if ok and type(c)=="table" then return c end
  return {}
end
local function save(data)
  local labels={}
  for k in pairs(data) do labels[#labels+1]=k end
  table.sort(labels)
  local lines={
    "-- Generated by Assembly Line Transposer Mapper v0.7",
    "-- Addresses change if a Transposer block is broken and replaced.",
    "return {"
  }
  for _,name in ipairs(labels) do
    local entry=data[name]
    lines[#lines+1]=string.format("  [%q]={address=%q,kind=%q,source=%s,destination=%s},",
      name,entry.address,entry.kind,
      entry.source and tostring(entry.source) or "nil",
      entry.destination and tostring(entry.destination) or "nil")
  end
  lines[#lines+1]="}"
  local h,err=io.open(path,"w")
  if not h then print("ERROR: Cannot save: "..tostring(err));return false end
  h:write(table.concat(lines,"\n").."\n")
  h:close()
  print("Saved mappings to "..path)
  return true
end
local function describe(addr)
  print("  Transposer "..addr)
  for side=0,5 do
    local inv=invoke(addr,"getInventorySize",side)
    local tanks=invoke(addr,"getTankCount",side)
    if type(inv)=="number" or (type(tanks)=="number" and tanks>0) then
      local invName=invoke(addr,"getInventoryName",side)
      print("    Side "..side.." | slots="..tostring(inv)..
        " | tanks="..tostring(tanks)..
        " | inventoryName="..tostring(invName))
    end
  end
end
local function findPrefix(prefix)
  if type(prefix)~="string" or #prefix<4 then
    return nil,"Use at least the first 4 characters of the Transposer address from the Analyzer"
  end
  local hits={}
  for _,addr in ipairs(available()) do
    if addr:sub(1,#prefix)==prefix then hits[#hits+1]=addr end
  end
  if #hits~=1 then return nil,"Address prefix matched "..#hits.." connected Transposers; expected exactly one" end
  return hits[1]
end
local function list()
  local data=load()
  local labels={}
  for label in pairs(data) do labels[#labels+1]=label end
  table.sort(labels)
  print("Saved routes: "..#labels)
  for _,label in ipairs(labels) do
    local r=data[label]
    local visible=false
    for _,a in ipairs(available()) do if a==r.address then visible=true end end
    print(string.format("  %s [%s] %s | source=%s destination=%s | %s",
      label,r.kind,short(r.address),tostring(r.source),tostring(r.destination),
      visible and "CONNECTED" or "OFFLINE"))
  end
end
local function scan()
  local addr=available()
  print("Connected Transposers: "..#addr)
  for _,a in ipairs(addr) do describe(a) end
  print("No materials moved.")
end
local function register()
  local label,kind,prefix=args[2],args[3],args[4]
  if not label or not label:match("^[%w_%-]+$") or
    (kind~="item" and kind~="fluid") then
    print("Usage: register <name> <item|fluid> <address-prefix>");return
  end
  local addr,err=findPrefix(prefix)
  if not addr then print("ERROR: "..err);return end
  local data=load()
  if data[label] then
    print("ERROR: "..label.." is already registered. Use another name, or remove it first.");return
  end
  for name,route in pairs(data) do
    if route.address==addr then
      print("ERROR: This Transposer is already registered as "..name);return
    end
  end
  data[label]={address=addr,kind=kind}
  if save(data) then
    print("Registered "..label.." ["..kind.."] -> "..addr)
    describe(addr)
  end
end
local function sides()
  local label=args[2]
  local src=tonumber(args[3])
  local dst=tonumber(args[4])
  if not label or not src or not dst or src~=math.floor(src) or dst~=math.floor(dst)
    or src<0 or src>5 or dst<0 or dst>5 or src==dst then
    print("Usage: sides <name> <source-side 0..5> <destination-side 0..5>")
    return
  end
  local data=load()
  local r=data[label]
  if not r then print("ERROR: Unknown name "..label);return end
  local ok=false
  for _,a in ipairs(available()) do if a==r.address then ok=true end end
  if not ok then print("ERROR: Transposer is not connected");return end
  local method=r.kind=="item" and "getInventorySize" or "getTankCount"
  local a=invoke(r.address,method,src)
  local b=invoke(r.address,method,dst)
  if type(a)~="number" or a<1 or type(b)~="number" or b<1 then
    print("ERROR: Both sides must expose readable "..(r.kind=="item" and "inventories" or "tanks"))
    print("Source "..src.."="..tostring(a)..", destination "..dst.."="..tostring(b))
    return
  end
  r.source=src
  r.destination=dst
  if save(data) then print(label..": source "..src.." -> destination "..dst.." | "..r.kind) end
end
local function remove()
  local label=args[2]
  local data=load()
  if not label or not data[label] then print("Usage: remove <existing-name>");return end
  data[label]=nil
  if save(data) then print("Unregistered "..label.." (no blocks modified)") end
end
if command=="scan" then scan()
elseif command=="list" then list()
elseif command=="register" then register()
elseif command=="sides" then sides()
elseif command=="remove" then remove()
else
  print("Assembly Line Transposer Mapper v0.7 | READ ONLY")
  print("scan")
  print("register <name> <item|fluid> <address-prefix>")
  print("sides <name> <source-side> <destination-side>")
  print("list")
  print("remove <name>")
  print("Names: bus1..bus16, hatch1..hatch4. Data Sticks remain manual.")
end